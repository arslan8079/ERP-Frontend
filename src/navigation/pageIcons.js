const pageIconTones = {
  Administration: 'red',
  'Human Resource': 'purple',
  Payroll: 'blue',
  'Finance & Accounting': 'orange',
  'Inventory & Warehouse': 'green',
  'Dealer Management': 'teal',
  'Reports & Analytics': 'purple',
}
export const pageIconFor = (page, moduleName) => {
  const label = page === 'Company Profile' ? 'Company Setup' : page
  const Icon = pageIconsByModule[moduleName]?.[label]
  if (!Icon) throw new Error(`No page icon configured for "${label}" in "${moduleName}"`)
  return { Icon, tone: label === dashboardTab ? 'green' : pageIconTones[moduleName] || 'red' }
}
